interface I18nContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

const STORAGE_KEY = 'obozon-lang';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    if (typeof localStorage === 'undefined') return 'de';
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Language | null;
      if (saved && ['de', 'en', 'ru', 'ky'].includes(saved)) return saved;
    } catch {
      // ignore
    }
    return 'de';
  });

  useEffect(() => {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY, lang);
    }
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((newLang: Language) => setLangState(newLang), []);

  const t = useCallback((key: string): string => translations[lang][key] ?? key, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
